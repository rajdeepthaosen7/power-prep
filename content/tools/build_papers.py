"""Turn the whole-paper files (content/gate-papers/*.yml) into one repeatable Flyway migration.

    python3 content/tools/build_papers.py

reads   content/gate-papers/*.yml (one file per paper set) and content/gate-papers/figures/*.svg
writes  src/main/resources/db/migration/R__content_zz_gate_papers.sql  (runs after the subject content files)

A paper file holds the questions of one paper that are NOT in a written chapter (see docs/pyq-plan.md, phase 3).
Questions of a written chapter live in that chapter's questions-*.yml; this script refuses a question that a chapter
file already claims. When a chapter is written later, move its questions from the paper file into the chapter file
with the same `key`: the database row (and every attempt on it) stays the same.

Each question fills the paper's "skeleton" row (source + question number, topic and marks already tagged) when there is
one, keeping its topic unless `topic` is given. Without a skeleton row (old papers), `topic` is required.

File shape:
    paper: {source: GATE-2016, q_prefix: "S1-Q", key_prefix: gate2016-s1, title: "GATE EE 2016, Set 1"}
    questions:
      - n: 12                 # question number in the paper
        marks: 1
        type: NAT             # MCQ | MSQ | NAT
        nat: {min: 18, max: 20}
        stem: |
        options: [{label: A, md: "...", correct: true}, ...]   # NAT: 4 options for APSC style (one correct)
        mcq_options: [...]    # MSQ only: single-answer version for APSC style
        solution: |
        status: OFFICIAL_KEY  # default: the paper's official key
        difficulty: 2
        topic: some-topic-slug          # optional (required without a skeleton row)
        also: [{code: APGCL-2023, q: "36", marks: 1}]   # the same question in other papers
"""
import glob
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(__file__))
from build_sql import ROOT, TAG, figure_keys, q, source_meta, summary_of  # noqa: E402

PAPERS = os.path.join(ROOT, "content", "gate-papers")
OUT = os.path.join(ROOT, "src", "main", "resources", "db", "migration", "R__content_zz_gate_papers.sql")


def chapter_claims():
    """(source code, q_no) pairs already written in a subject's chapter files."""
    claims = {}
    for f in glob.glob(os.path.join(ROOT, "content", "*", "*", "questions-*.yml")):
        for it in yaml.safe_load(open(f, encoding="utf-8")) or []:
            for s in it.get("sources") or []:
                claims[(s["code"], str(s["q"]))] = f"{os.path.relpath(f, ROOT)} ({it['key']})"
    return claims


def main():
    claims = chapter_claims()
    out = ["-- GENERATED by content/tools/build_papers.py from content/gate-papers/ . Do not edit by hand.",
           "-- Repeatable migration: fills whole GATE papers question by question (upserts by content key).", ""]
    files = sorted(glob.glob(os.path.join(PAPERS, "*.yml")))
    seen, codes, n_q = set(), set(), 0
    blocks = []
    for f in files:
        doc = yaml.safe_load(open(f, encoding="utf-8"))
        p = doc["paper"]
        for it in doc.get("questions") or []:
            qno = f"{p.get('q_prefix', '')}{it['n']}"
            key = f"{p['key_prefix']}-q{it['n']}"
            assert key not in seen, "duplicate key " + key
            seen.add(key)
            clash = claims.get((p["source"], qno))
            assert not clash, f"{key}: {p['source']} {qno} is already written in {clash}"
            typ = it["type"]
            opts = it.get("options") or []
            mcq = it.get("mcq_options") or []
            nat = it.get("nat") or {}
            if typ in ("MCQ", "MSQ"):
                assert len(opts) >= 2 and any(o.get("correct") for o in opts), "no correct option in " + key
            if typ == "MCQ":
                assert sum(bool(o.get("correct")) for o in opts) == 1, "MCQ needs exactly one correct option: " + key
            if typ == "NAT":
                assert nat.get("min") is not None and nat.get("max") is not None, "NAT without range: " + key
                assert len(opts) == 4 and sum(bool(o.get("correct")) for o in opts) == 1, "NAT needs 4 APSC-style options, one correct: " + key
            if mcq:
                assert typ == "MSQ" and len(mcq) == 4 and sum(bool(o.get("correct")) for o in mcq) == 1, "bad mcq_options: " + key
            for o in opts + mcq:
                assert o["label"] in ("A", "B", "C", "D", "E"), "bad option label in " + key
            sources = [{"code": p["source"], "q": qno, "marks": it["marks"], "primary": True}] + \
                      [dict(s, primary=False) for s in it.get("also") or []]
            for s in sources:
                codes.add(s["code"])
            stem, sol = it["stem"].strip() + "\n", it["solution"].strip() + "\n"
            status = it.get("status", "OFFICIAL_KEY")
            topic = it.get("topic")
            pairs = ", ".join(f"({q(s['code'])}, {q(str(s['q']))})" for s in sources)
            b = [f"DO {TAG}", "DECLARE qid int; tid int; subj int;", "BEGIN",
                 f"  SELECT id INTO qid FROM question WHERE content_key = {q(key)};",
                 "  IF qid IS NULL THEN",
                 "    SELECT qs.question_id INTO qid FROM question_source qs JOIN source s ON s.id = qs.source_id",
                 "      JOIN question x ON x.id = qs.question_id",
                 f"      WHERE (s.code, qs.q_no) IN ({pairs}) AND x.content_key IS NULL ORDER BY qs.question_id LIMIT 1;",
                 "  END IF;"]
            if topic:
                b.append(f"  SELECT t.id, t.subject_id INTO tid, subj FROM topic t WHERE t.slug = {q(topic)} ORDER BY t.id LIMIT 1;")
                b.append(f"  IF tid IS NULL THEN RAISE EXCEPTION 'paper question {key}: unknown topic {topic}'; END IF;")
            b += ["  IF qid IS NULL THEN",
                  f"    IF tid IS NULL THEN RAISE EXCEPTION 'paper question {key}: no skeleton row, give a topic'; END IF;",
                  "    INSERT INTO question(subject_id, topic_id, summary, stem_md, solution_md, status, answer_type, nat_min, nat_max,",
                  "                         difficulty, answer_status, content_key, origin)",
                  f"    VALUES (subj, tid, {q(summary_of(stem))}, {q(stem)}, {q(sol)}, 'READY', {q(typ)}, {q(nat.get('min'))}, {q(nat.get('max'))}, "
                  f"{it.get('difficulty', 2)}, {q(status)}, {q(key)}, 'PYQ') RETURNING id INTO qid;",
                  "  ELSE",
                  f"    UPDATE question SET topic_id = COALESCE(tid, topic_id), subject_id = COALESCE(subj, subject_id), "
                  f"summary = COALESCE(NULLIF(summary, ''), {q(summary_of(stem))}), stem_md = {q(stem)}, solution_md = {q(sol)}, "
                  f"status = 'READY', answer_type = {q(typ)}, nat_min = {q(nat.get('min'))}, nat_max = {q(nat.get('max'))}, "
                  f"difficulty = {it.get('difficulty', 2)}, answer_status = {q(status)}, content_key = {q(key)}, origin = 'PYQ', "
                  "updated_at = now() WHERE id = qid;",
                  "  END IF;"]
            for s in sources:
                b.append(f"  INSERT INTO question_source(source_id, q_no, question_id, marks, is_primary) VALUES "
                         f"((SELECT id FROM source WHERE code = {q(s['code'])}), {q(str(s['q']))}, qid, {q(s.get('marks'))}, {q(bool(s['primary']))}) "
                         "ON CONFLICT (source_id, q_no) DO UPDATE SET question_id = EXCLUDED.question_id, marks = EXCLUDED.marks, "
                         "is_primary = EXCLUDED.is_primary;")
            labels = [o["label"] for o in opts]
            b.append("  DELETE FROM question_option WHERE question_id = qid"
                     + (f" AND label NOT IN ({', '.join(q(l) for l in labels)});" if labels else ";"))
            for o in opts:
                b.append(f"  INSERT INTO question_option(question_id, label, body_md, is_correct) VALUES (qid, {q(o['label'])}, {q(str(o['md']))}, "
                         f"{q(bool(o.get('correct')))}) ON CONFLICT (question_id, label) DO UPDATE SET body_md = EXCLUDED.body_md, is_correct = EXCLUDED.is_correct;")
            b.append("  DELETE FROM question_mcq_option WHERE question_id = qid;")
            for o in mcq:
                b.append(f"  INSERT INTO question_mcq_option(question_id, label, body_md, is_correct) VALUES (qid, {q(o['label'])}, "
                         f"{q(str(o['md']))}, {q(bool(o.get('correct')))});")
            fkeys = []
            for md in [stem, sol] + [str(o["md"]) for o in opts + mcq]:
                for fk in figure_keys(md):
                    if fk not in fkeys:
                        fkeys.append(fk)
            for k, fk in enumerate(fkeys, 1):
                svg = open(os.path.join(PAPERS, "figures", fk + ".svg"), encoding="utf-8").read()
                b.append(f"  INSERT INTO figure(question_id, storage_key, svg, sort_order) VALUES (qid, {q(fk)}, {q(svg)}, {k}) "
                         "ON CONFLICT (storage_key) DO UPDATE SET question_id = EXCLUDED.question_id, concept_section_id = NULL, "
                         "svg = EXCLUDED.svg, sort_order = EXCLUDED.sort_order;")
            b.append(f"END {TAG};")
            blocks.append("\n".join(b))
            n_q += 1
    out.append("-- sources")
    for code in sorted(codes):
        kind, exam, year, title = source_meta(code)
        out.append(f"INSERT INTO source(code, kind, exam, year, title) VALUES ({q(code)}, {q(kind)}, {q(exam)}, {year}, {q(title)}) "
                   "ON CONFLICT (code) DO NOTHING;")
    out.append("\n-- questions")
    out += blocks
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {n_q} questions from {len(files)} paper file(s)")


if __name__ == "__main__":
    main()
