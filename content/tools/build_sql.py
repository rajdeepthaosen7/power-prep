"""Turn the content files of one subject into a repeatable Flyway migration.

    python3 content/tools/build_sql.py electric-circuits

reads   content/<subject>/chapters.yml, the chapter folders (notes/*.md, questions-*.yml, figures/*.svg)
writes  src/main/resources/db/migration/R__content_<subject_with_underscores>.sql

The migration is idempotent (upserts by natural keys), so Flyway re-runs it whenever the content changes.
Never hand-edit the generated SQL: edit the content files and run this script again.
"""
import glob
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TAG = "$ppimport$"


def q(s):
    """SQL string literal (standard_conforming_strings = on: only quotes need doubling)."""
    if s is None:
        return "NULL"
    if isinstance(s, bool):
        return "TRUE" if s else "FALSE"
    if isinstance(s, (int, float)):
        return repr(s)
    s = str(s)
    if TAG in s:
        raise ValueError("content contains the reserved tag " + TAG)
    return "'" + s.replace("'", "''") + "'"


def figure_keys(md):
    return re.findall(r"\(fig:([a-z0-9-]+)\)", md or "")


def summary_of(stem):
    s = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", stem)
    s = re.sub(r"[*_`#>]", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= 160 else s[:157].rsplit(" ", 1)[0] + "..."


def source_meta(code):
    m = re.match(r"([A-Z]+)-(\d{4})", code)
    exam, year = m.group(1), int(m.group(2))
    kind = {"GATE": "GATE", "ESE": "ESE"}.get(exam, "STATE")
    title = {"ESE": f"UPSC ESE Prelims {year}, Paper II (Electrical)", "GATE": f"GATE EE {year}"}.get(exam)
    return kind, exam, year, title


def main(subject):
    base = os.path.join(ROOT, "content", subject)
    plan = yaml.safe_load(open(os.path.join(base, "chapters.yml")))
    S = f"(SELECT id FROM subject WHERE slug = {q(subject)})"
    out = [
        f"-- GENERATED by content/tools/build_sql.py from content/{subject}/ . Do not edit by hand.",
        "-- Repeatable migration: upserts chapters, topics, notes, figures and questions by natural keys.",
        "",
    ]

    questions, notes_by_topic, chapter_of_topic, mocks = [], {}, {}, []
    for ch in plan["chapters"]:
        for t in ch.get("topics", []):
            chapter_of_topic[t["slug"]] = ch["slug"]
        if ch.get("dir"):
            d = os.path.join(base, ch["dir"])
            for t in ch["topics"]:
                notes_by_topic[t["slug"]] = open(os.path.join(d, "notes", t["note"]), encoding="utf-8").read().strip() + "\n"
            files = sorted(glob.glob(os.path.join(d, "questions-*.yml"))) + sorted(glob.glob(os.path.join(d, "practice-*.yml")))
            for f in files:
                practice = os.path.basename(f).startswith("practice-")
                for item in yaml.safe_load(open(f, encoding="utf-8")) or []:
                    item["_dir"] = d
                    item["_origin"] = "PRACTICE" if practice else "PYQ"
                    item.setdefault("sources", [])
                    assert bool(item["sources"]) != practice, "practice questions have no sources, exam questions need one: " + item["key"]
                    questions.append(item)
            mf = os.path.join(d, "mocks.yml")
            if os.path.exists(mf):
                for m in yaml.safe_load(open(mf, encoding="utf-8")) or []:
                    m["_chapter"] = ch["slug"]
                    mocks.append(m)

    # ---- sources ----
    codes = sorted({s["code"] for it in questions for s in it["sources"]})
    out.append("-- sources")
    for code in codes:
        kind, exam, year, title = source_meta(code)
        out.append(f"INSERT INTO source(code, kind, exam, year, title) VALUES ({q(code)}, {q(kind)}, {q(exam)}, {year}, {q(title)}) "
                   f"ON CONFLICT (code) DO NOTHING;")

    # ---- chapters and topics ----
    out.append("\n-- chapters")
    for ch in plan["chapters"]:
        out.append(
            f"INSERT INTO chapter(subject_id, name, slug, sort_order, description) VALUES ({S}, {q(ch['name'])}, {q(ch['slug'])}, "
            f"{ch['sort']}, {q(ch.get('description'))}) ON CONFLICT (subject_id, slug) DO UPDATE SET name = EXCLUDED.name, "
            f"sort_order = EXCLUDED.sort_order, description = EXCLUDED.description, updated_at = now();")
    out.append("\n-- topics")
    for ch in plan["chapters"]:
        C = f"(SELECT id FROM chapter WHERE subject_id = {S} AND slug = {q(ch['slug'])})"
        for k, t in enumerate(ch.get("topics", []), 1):
            out.append(
                f"INSERT INTO topic(subject_id, chapter_id, name, slug, sort_order) VALUES ({S}, {C}, {q(t['name'])}, {q(t['slug'])}, {k}) "
                f"ON CONFLICT (subject_id, slug) DO UPDATE SET chapter_id = EXCLUDED.chapter_id, name = EXCLUDED.name, "
                f"sort_order = EXCLUDED.sort_order, updated_at = now();")
        if ch.get("legacy_topics"):
            lst = ", ".join(q(s) for s in ch["legacy_topics"])
            out.append(f"UPDATE topic SET chapter_id = {C}, updated_at = now() WHERE subject_id = {S} AND slug IN ({lst});")

    # ---- notes (one concept section per topic) and their figures ----
    out.append("\n-- notes")
    for k, (slug, body) in enumerate(notes_by_topic.items(), 1):
        T = f"(SELECT id FROM topic WHERE subject_id = {S} AND slug = {q(slug)})"
        name = next(t["name"] for ch in plan["chapters"] for t in ch.get("topics", []) if t["slug"] == slug)
        out.append(
            f"INSERT INTO concept_section(topic_id, sort_order, title, body_md, status, slug) VALUES ({T}, 1, {q(name)}, {q(body)}, 'PUBLISHED', 'main') "
            f"ON CONFLICT (topic_id, slug) DO UPDATE SET title = EXCLUDED.title, body_md = EXCLUDED.body_md, status = EXCLUDED.status, "
            f"version = concept_section.version + 1, updated_at = now() WHERE concept_section.body_md IS DISTINCT FROM EXCLUDED.body_md "
            f"OR concept_section.title IS DISTINCT FROM EXCLUDED.title;")
        CS = f"(SELECT cs.id FROM concept_section cs WHERE cs.topic_id = {T} AND cs.slug = 'main')"
        ch_dir = next(os.path.join(base, c["dir"]) for c in plan["chapters"] if c["slug"] == chapter_of_topic[slug])
        for n, fk in enumerate(figure_keys(body), 1):
            svg = open(os.path.join(ch_dir, "figures", fk + ".svg"), encoding="utf-8").read()
            out.append(
                f"INSERT INTO figure(concept_section_id, storage_key, svg, sort_order) VALUES ({CS}, {q(fk)}, {q(svg)}, {n}) "
                f"ON CONFLICT (storage_key) DO UPDATE SET concept_section_id = EXCLUDED.concept_section_id, question_id = NULL, "
                f"svg = EXCLUDED.svg, sort_order = EXCLUDED.sort_order;")

    # ---- questions ----
    out.append("\n-- questions")
    seen = set()
    for it in questions:
        key = it["key"]
        assert key not in seen, "duplicate key " + key
        seen.add(key)
        assert it["topic"] in chapter_of_topic, "unknown topic " + it["topic"]
        typ = it["type"]
        opts = it.get("options") or []
        if typ in ("MCQ", "MSQ"):
            assert len(opts) >= 2 and any(o.get("correct") for o in opts), "no correct option in " + key
        if typ == "NAT":
            assert it.get("nat"), "NAT without range in " + key
        nat = it.get("nat") or {}
        if it["_origin"] == "PRACTICE":
            assert typ == "MCQ" and len(opts) == 4, "practice questions are 4-option MCQs (APSC format): " + key
        if typ == "NAT" and opts:
            assert len(opts) == 4 and sum(bool(o.get("correct")) for o in opts) == 1, "NAT test options need 4 with one correct: " + key
        stem, sol = it["stem"].strip() + "\n", it["solution"].strip() + "\n"
        pairs = ", ".join(f"({q(s['code'])}, {q(str(s['q']))})" for s in it["sources"]) or "(NULL, NULL)"
        blk = [f"DO {TAG}", "DECLARE qid int; subj int; tid int;", "BEGIN",
               f"  SELECT id INTO subj FROM subject WHERE slug = {q(subject)};",
               f"  SELECT id INTO tid FROM topic WHERE subject_id = subj AND slug = {q(it['topic'])};",
               f"  SELECT id INTO qid FROM question WHERE content_key = {q(key)};",
               "  IF qid IS NULL THEN",
               "    SELECT qs.question_id INTO qid FROM question_source qs JOIN source s ON s.id = qs.source_id",
               "      JOIN question x ON x.id = qs.question_id",
               f"      WHERE (s.code, qs.q_no) IN ({pairs}) AND x.content_key IS NULL",
               "      ORDER BY qs.question_id LIMIT 1;",
               "  END IF;",
               "  IF qid IS NULL THEN",
               "    INSERT INTO question(subject_id, topic_id, nature, summary, stem_md, solution_md, status, answer_type, nat_min, nat_max,",
               "                         difficulty, answer_status, content_key, origin)",
               f"    VALUES (subj, tid, {q(it['nature'])}, {q(summary_of(stem))}, {q(stem)}, {q(sol)}, 'READY', {q(typ)}, "
               f"{q(nat.get('min'))}, {q(nat.get('max'))}, {it.get('difficulty', 2)}, {q(it['status'])}, {q(key)}, {q(it['_origin'])}) RETURNING id INTO qid;",
               "  ELSE",
               f"    UPDATE question SET subject_id = subj, topic_id = tid, nature = {q(it['nature'])}, "
               f"summary = COALESCE(NULLIF(summary, ''), {q(summary_of(stem))}), stem_md = {q(stem)}, solution_md = {q(sol)}, status = 'READY', "
               f"answer_type = {q(typ)}, nat_min = {q(nat.get('min'))}, nat_max = {q(nat.get('max'))}, difficulty = {it.get('difficulty', 2)}, "
               f"answer_status = {q(it['status'])}, content_key = {q(key)}, origin = {q(it['_origin'])}, updated_at = now() WHERE id = qid;",
               "  END IF;"]
        for s in it["sources"]:
            primary = s.get("primary", len(it["sources"]) == 1)
            blk.append(
                f"  INSERT INTO question_source(source_id, q_no, question_id, marks, is_primary, source_url) VALUES "
                f"((SELECT id FROM source WHERE code = {q(s['code'])}), {q(str(s['q']))}, qid, {q(s.get('marks'))}, {q(bool(primary))}, {q(s.get('url'))}) "
                f"ON CONFLICT (source_id, q_no) DO UPDATE SET question_id = EXCLUDED.question_id, marks = EXCLUDED.marks, "
                f"is_primary = EXCLUDED.is_primary, source_url = EXCLUDED.source_url;")
        labels = [o["label"] for o in opts]
        blk.append(f"  DELETE FROM question_option WHERE question_id = qid"
                   + (f" AND label NOT IN ({', '.join(q(l) for l in labels)});" if labels else ";"))
        for o in opts:
            blk.append(f"  INSERT INTO question_option(question_id, label, body_md, is_correct) VALUES (qid, {q(o['label'])}, {q(str(o['md']))}, "
                       f"{q(bool(o.get('correct')))}) ON CONFLICT (question_id, label) DO UPDATE SET body_md = EXCLUDED.body_md, is_correct = EXCLUDED.is_correct;")
        fkeys = []
        for md in [stem, sol] + [str(o["md"]) for o in opts]:
            for fk in figure_keys(md):
                if fk not in fkeys:
                    fkeys.append(fk)
        for n, fk in enumerate(fkeys, 1):
            svg = open(os.path.join(it["_dir"], "figures", fk + ".svg"), encoding="utf-8").read()
            blk.append(f"  INSERT INTO figure(question_id, storage_key, svg, sort_order) VALUES (qid, {q(fk)}, {q(svg)}, {n}) "
                       f"ON CONFLICT (storage_key) DO UPDATE SET question_id = EXCLUDED.question_id, concept_section_id = NULL, "
                       f"svg = EXCLUDED.svg, sort_order = EXCLUDED.sort_order;")
        concepts = it.get("concepts") or [it["topic"]]
        blk.append("  DELETE FROM question_concept WHERE question_id = qid;")
        blk.append(f"  INSERT INTO question_concept(question_id, concept_section_id) SELECT qid, cs.id FROM concept_section cs "
                   f"JOIN topic t ON t.id = cs.topic_id WHERE t.subject_id = subj AND cs.slug = 'main' "
                   f"AND t.slug IN ({', '.join(q(c) for c in concepts)});")
        blk.append(f"END {TAG};")
        out.append("\n".join(blk))

    # ---- mock tests (content/<subject>/<chapter>/mocks.yml) ----
    out.append("\n-- mock tests")
    by_key = {it["key"]: it for it in questions}
    for n, m in enumerate(mocks, 1):
        keys = m["questions"]
        assert len(keys) == len(set(keys)), "repeated question in mock " + m["code"]
        for k in keys:
            it = by_key.get(k)
            assert it, f"mock {m['code']}: unknown question {k}"
            assert it["type"] == "MCQ" or (it["type"] == "NAT" and it.get("options")), f"mock {m['code']}: {k} has no MCQ form"
            if m["variant"] == "PYQ":
                assert it["_origin"] == "PYQ", f"PYQ mock {m['code']} has our question {k}"
            if m["variant"] == "FRESH":
                assert it["_origin"] == "PRACTICE", f"FRESH mock {m['code']} has exam question {k}"
        minutes = -(-len(keys) * 6 // 5)          # APSC pace: 100 questions in 120 minutes
        C = f"(SELECT id FROM chapter WHERE subject_id = {S} AND slug = {q(m['_chapter'])})"
        out.append(
            f"INSERT INTO test(code, title, kind, duration_min, marks_correct, marks_wrong, status, subject_id, chapter_id, variant, description, sort_order) "
            f"VALUES ({q(m['code'])}, {q(m['title'])}, 'CHAPTER', {minutes}, 1, 0.25, 'PUBLISHED', {S}, {C}, {q(m['variant'])}, "
            f"{q(m.get('description'))}, {n}) ON CONFLICT (code) DO UPDATE SET title = EXCLUDED.title, kind = EXCLUDED.kind, "
            f"duration_min = EXCLUDED.duration_min, marks_correct = EXCLUDED.marks_correct, marks_wrong = EXCLUDED.marks_wrong, "
            f"status = EXCLUDED.status, subject_id = EXCLUDED.subject_id, chapter_id = EXCLUDED.chapter_id, variant = EXCLUDED.variant, "
            f"description = EXCLUDED.description, sort_order = EXCLUDED.sort_order, updated_at = now();")
        T = f"(SELECT id FROM test WHERE code = {q(m['code'])})"
        out.append(f"DELETE FROM test_question WHERE test_id = {T};")
        rows = ", ".join(f"({pos}, {q(k)})" for pos, k in enumerate(keys, 1))
        out.append(f"INSERT INTO test_question(test_id, position, question_id, section) SELECT {T}, v.pos, qq.id, NULL "
                   f"FROM (VALUES {rows}) AS v(pos, k) JOIN question qq ON qq.content_key = v.k;")

    # ---- one-off fixes of earlier tagging ----
    out.append("\n-- fixes")
    for fx in plan.get("fixes", []):
        subj = f"(SELECT id FROM subject WHERE slug = {q(fx.get('subject', subject))})"
        sets = [f"subject_id = {subj}",
                f"topic_id = (SELECT id FROM topic WHERE subject_id = {subj} AND slug = {q(fx['topic'])})", "updated_at = now()"]
        if fx.get("summary"):
            sets.append(f"summary = {q(fx['summary'])}")
        out.append(f"UPDATE question SET {', '.join(sets)} WHERE id IN (SELECT qs.question_id FROM question_source qs JOIN source s "
                   f"ON s.id = qs.source_id WHERE s.code = {q(fx['source'])} AND qs.q_no = {q(str(fx['q']))}) AND content_key IS NULL;")

    # ---- clean-up: merged duplicates and retired topics ----
    out.append("\n-- clean-up")
    out.append("DELETE FROM question_link l WHERE NOT EXISTS (SELECT 1 FROM question_source qs WHERE qs.question_id = l.gate_question_id) "
               "OR NOT EXISTS (SELECT 1 FROM question_source qs WHERE qs.question_id = l.state_question_id);")
    out.append("DELETE FROM question q WHERE q.origin = 'PYQ' AND NOT EXISTS (SELECT 1 FROM question_source qs WHERE qs.question_id = q.id) "
               "AND NOT EXISTS (SELECT 1 FROM attempt a WHERE a.question_id = q.id) "
               "AND NOT EXISTS (SELECT 1 FROM user_question_state u WHERE u.question_id = q.id) "
               "AND NOT EXISTS (SELECT 1 FROM test_question tq WHERE tq.question_id = q.id);")
    retire = [s for ch in plan["chapters"] for s in ch.get("retire_legacy_topics", [])] + plan.get("delete_empty_topics", [])
    if retire:
        out.append(f"DELETE FROM topic t WHERE t.subject_id = {S} AND t.slug IN ({', '.join(q(s) for s in retire)}) "
                   "AND NOT EXISTS (SELECT 1 FROM question x WHERE x.topic_id = t.id) "
                   "AND NOT EXISTS (SELECT 1 FROM concept_section c WHERE c.topic_id = t.id) "
                   "AND NOT EXISTS (SELECT 1 FROM syllabus_item_topic st WHERE st.topic_id = t.id);")

    dst = os.path.join(ROOT, "src", "main", "resources", "db", "migration", f"R__content_{subject.replace('-', '_')}.sql")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(dst, ROOT)}: {len(questions)} questions, {len(notes_by_topic)} notes, {len(codes)} sources, {len(mocks)} mocks")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "electric-circuits")
