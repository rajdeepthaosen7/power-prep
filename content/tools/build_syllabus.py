"""Turn content/syllabus/<exam>.yml into the repeatable migration R__syllabus.sql.

    python3 content/tools/build_syllabus.py

Sections become top-level syllabus_item rows (code "2", "3", ...), items become children ("2.01", ...),
and each item is linked to its topics (subject-scoped). Upserts by (exam_code, code); stale rows are removed.
"""
import glob
import os

import yaml

from build_sql import ROOT, q


def main():
    out = ["-- GENERATED by content/tools/build_syllabus.py from content/syllabus/*.yml . Do not edit by hand.", ""]
    for path in sorted(glob.glob(os.path.join(ROOT, "content", "syllabus", "*.yml"))):
        d = yaml.safe_load(open(path, encoding="utf-8"))
        ex = d["exam"]
        codes = []
        for si, sec in enumerate(d["sections"], 1):
            S = f"(SELECT id FROM subject WHERE slug = {q(sec['subject'])})"
            codes.append(sec["code"])
            out.append(f"INSERT INTO syllabus_item(exam_code, code, parent_id, text, sort_order, subject_id, note) VALUES "
                       f"({q(ex)}, {q(sec['code'])}, NULL, {q(sec['text'])}, {si}, {S}, {q(sec.get('note'))}) "
                       f"ON CONFLICT (exam_code, code) DO UPDATE SET parent_id = NULL, text = EXCLUDED.text, sort_order = EXCLUDED.sort_order, "
                       f"subject_id = EXCLUDED.subject_id, note = EXCLUDED.note;")
            P = f"(SELECT id FROM syllabus_item WHERE exam_code = {q(ex)} AND code = {q(sec['code'])})"
            for ii, it in enumerate(sec["items"], 1):
                code = f"{sec['code']}.{ii:02d}"
                codes.append(code)
                out.append(f"INSERT INTO syllabus_item(exam_code, code, parent_id, text, sort_order, subject_id, note) VALUES "
                           f"({q(ex)}, {q(code)}, {P}, {q(it['text'])}, {ii}, {S}, {q(it.get('note'))}) "
                           f"ON CONFLICT (exam_code, code) DO UPDATE SET parent_id = EXCLUDED.parent_id, text = EXCLUDED.text, "
                           f"sort_order = EXCLUDED.sort_order, subject_id = EXCLUDED.subject_id, note = EXCLUDED.note;")
                I = f"(SELECT id FROM syllabus_item WHERE exam_code = {q(ex)} AND code = {q(code)})"
                out.append(f"DELETE FROM syllabus_item_topic WHERE syllabus_item_id = {I};")
                if it["topics"]:
                    lst = ", ".join(q(t) for t in it["topics"])
                    TS = f"(SELECT id FROM subject WHERE slug = {q(it['subject'])})" if it.get("subject") else S  # item taught in another subject
                    out.append(f"INSERT INTO syllabus_item_topic(syllabus_item_id, topic_id) SELECT {I}, t.id FROM topic t "
                               f"WHERE t.subject_id = {TS} AND t.slug IN ({lst}) ON CONFLICT DO NOTHING;")
        keep = ", ".join(q(c) for c in codes)
        out.append(f"DELETE FROM syllabus_item WHERE exam_code = {q(ex)} AND parent_id IS NOT NULL AND code NOT IN ({keep});")
        out.append(f"DELETE FROM syllabus_item WHERE exam_code = {q(ex)} AND code NOT IN ({keep});")
    dst = os.path.join(ROOT, "src", "main", "resources", "db", "migration", "R__syllabus.sql")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(dst, ROOT), sum(1 for l in out if l.startswith("INSERT INTO syllabus_item(")), "items")


if __name__ == "__main__":
    main()
